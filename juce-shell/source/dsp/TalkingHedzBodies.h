static inline FilterFrame<6> makeFrame(const std::array<std::array<uint16_t, 5>, 6>& src) {
    FilterFrame<6> f;
    for (int i = 0; i < 6; ++i)
        for (int w = 0; w < 5; ++w)
            f.stages[i].w[w] = src[i][w];
    return f;
}

static inline FilterFrame<6> getM0_Q0() { return makeFrame(M0_Q0); }
static inline FilterFrame<6> getM0_Q100() { return makeFrame(M0_Q100); }
static inline FilterFrame<6> getM100_Q0() { return makeFrame(M100_Q0); }
static inline FilterFrame<6> getM100_Q100() { return makeFrame(M100_Q100); }


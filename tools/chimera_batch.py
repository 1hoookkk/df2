#!/usr/bin/env python3
"""chimera_batch — reference-guided ORIGINAL authoring of whole 4-corner bodies.

The second half of the Chimera workflow. NOT a ROM copier.

Pipeline:
  1. Describe each `--stocks` reference (.bin) -> response descriptors only
     (via tools.chimera_describe_refs; no coefficients are read out as reusable).
  2. BLEND those descriptors into one target recipe (mean band balance, pooled
     peak regions, mean Morph/Q motion, radius guardrail).
  3. GENERATE original whole 4-corner candidates with the repo-safe generator
     (tools.batch_complex.rand_body — peaking-EQ baseline + a motion strategy,
     rolled from a seed). These coefficients come from the generator, never from
     any reference. The blend only RANKS which originals we keep.
  4. Gate each finalist: stability + no-pedestal/response-budget
     (tools.response_budget.judge), plus a similarity-to-stock ORIGINALITY warning
     (a candidate too close to a single stock is flagged, not shipped silently).
  5. Write per-candidate: target recipe, .cart.json, .body240, report.

If the generator cannot produce a single clean candidate, the run STOPS after
writing the target recipes and a clear BLOCKED report. It never fakes bodies.

Run (handoff smoke command):
  python tools/chimera_batch.py --stocks \
      ref/presets/P2k_013_talking_hedz.bin \
      ref/presets/P2k_015_dj_alkaline.bin \
      ref/presets/P2k_031_ear_bender.bin \
      --count 12 --out dev/tmp/chimera_batch_smoke
"""
